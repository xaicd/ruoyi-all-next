/**
 * Codegen Engine - 低代码生成引擎
 *
 * 核心能力：
 * 1. 从数据库表结构 → 生成完整模块代码（Service/Validator/Route/Page）
 * 2. 支持多种模板（CRUD/Tree/Workflow/Singleton）
 * 3. 支持多端生成（admin/app/miniprogram）
 * 4. 支持预览 + 下载 + 直接写入项目
 *
 * 对标 RuoYi CodegenEngine + CodegenBuilder
 */

import { domainLog } from "@/modules/shared/backend/lib/domain-log"
import type { TableInfo, ColumnInfo, UiComponentType } from "./schema-reader.service"

// ============ Types ============

export type CodegenScene = "ADMIN" | "APP" | "MINIPROGRAM"

export type CodegenTemplate =
  | "CRUD"           // 标准增删改查
  | "TREE"           // 树形结构（部门/菜单/分类）
  | "MASTER_CHILD"   // 主子表（订单+订单项）
  | "WORKFLOW"       // 工作流审批
  | "SINGLETON"      // 单例配置页

export type CodegenConfig = {
  /** 模块名（域），如 system, mall */
  moduleName: string
  /** 子域名，如 product, trade */
  subModule?: string
  /** 业务名称（中文），如 "商品" */
  businessName: string
  /** 类名前缀，如 Product */
  className: string
  /** 模板类型 */
  template: CodegenTemplate
  /** 生成场景 */
  scene: CodegenScene
  /** 表信息 */
  table: TableInfo
  /** 作者 */
  author?: string
  /** 是否生成前端 */
  generateFrontend: boolean
  /** 是否生成测试 */
  generateTest: boolean
  /** 父菜单 ID（用于菜单注册） */
  parentMenuId?: string
  /** 主子表配置 */
  masterChild?: {
    childTable: TableInfo
    childForeignKey: string
  }
}

export type CodegenOutput = {
  /** 文件路径（相对项目根） */
  path: string
  /** 文件内容 */
  content: string
  /** 文件类型 */
  type: "service" | "validator" | "route" | "page" | "component" | "test" | "type" | "repository"
}

// ============ Service ============

export class CodegenEngineService {
  /**
   * 生成完整模块代码
   */
  static generate(config: CodegenConfig): CodegenOutput[] {
    domainLog.event("infra.codegen.generate", {
      moduleName: config.moduleName,
      className: config.className,
      template: config.template,
      scene: config.scene,
    })

    const outputs: CodegenOutput[] = []

    // 1. 类型定义
    outputs.push(generateTypes(config))

    // 2. Validator (Zod Schema)
    outputs.push(generateValidator(config))

    // 3. Service
    outputs.push(generateService(config))

    // 4. API Route
    outputs.push(generateRoute(config))

    // 5. 前端页面
    if (config.generateFrontend) {
      outputs.push(generateListPage(config))
      outputs.push(generateFormComponent(config))
      outputs.push(generateAppPageEntry(config))
    }

    // 6. 测试
    if (config.generateTest) {
      outputs.push(generateTest(config))
    }

    domainLog.audit("infra.codegen.generate", {
      targetType: "CODEGEN",
      targetId: config.className,
      fileCount: outputs.length,
    })

    return outputs
  }

  /**
   * 预览生成结果（不写入文件）
   */
  static preview(config: CodegenConfig): CodegenOutput[] {
    return CodegenEngineService.generate(config)
  }

  /**
   * 获取可用模板列表
   */
  static listTemplates(): { id: CodegenTemplate; name: string; description: string }[] {
    return [
      { id: "CRUD", name: "标准CRUD", description: "列表+新增+编辑+删除，适用于大部分管理页面" },
      { id: "TREE", name: "树形结构", description: "树形展示+新增+编辑，适用于部门/分类/菜单" },
      { id: "MASTER_CHILD", name: "主子表", description: "主表+子表，适用于订单+订单项" },
      { id: "WORKFLOW", name: "工作流", description: "带审批流程的业务表单" },
      { id: "SINGLETON", name: "单例配置", description: "系统配置页（只有一条记录）" },
    ]
  }
}

// ============ Generator Functions ============

function toKebab(str: string): string {
  return str.replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase()
}

function toCamel(str: string): string {
  return str[0].toLowerCase() + str.slice(1)
}

function getBasePath(config: CodegenConfig): string {
  const sub = config.subModule ? `/${config.subModule}` : ""
  return `src/modules/${config.moduleName}${sub}`
}

function generateTypes(config: CodegenConfig): CodegenOutput {
  const { className, table } = config
  const fields = table.columns
    .filter((c) => c.name !== "deleted")
    .map((c) => `  ${c.name}: ${c.tsType}${c.nullable ? " | null" : ""}`)
    .join("\n")

  const content = `// Auto-generated by Codegen Engine
// Table: ${table.name} | ${table.comment || className}

export type ${className}DO = {
${fields}
}

export type ${className}VO = ${className}DO

export type ${className}CreateInput = Omit<${className}DO, "id" | "created_at" | "updated_at">

export type ${className}UpdateInput = Partial<${className}CreateInput> & { id: string }

export type ${className}PageQuery = {
  page: number
  pageSize: number
  keyword?: string
}
`
  return { path: `${getBasePath(config)}/types/${toKebab(className)}.types.ts`, content, type: "type" }
}

function generateValidator(config: CodegenConfig): CodegenOutput {
  const { className, table } = config
  const kebab = toKebab(className)

  const createFields = table.columns
    .filter((c) => !c.isPrimary && !c.isAutoIncrement && c.name !== "created_at" && c.name !== "updated_at" && c.name !== "deleted")
    .map((c) => {
      let zodType = "z.string()"
      if (c.tsType === "number") zodType = "z.coerce.number()"
      if (c.tsType === "boolean") zodType = "z.boolean()"
      if (c.nullable) zodType += ".optional()"
      else zodType += `.min(1, "${c.comment || c.name} 不能为空")`
      if (c.maxLength) zodType = zodType.replace(".min(1", `.min(1`).replace("z.string()", `z.string().max(${c.maxLength})`)
      return `  ${c.name}: ${zodType},`
    })
    .join("\n")

  const content = `// Auto-generated by Codegen Engine
import { z } from "zod"

export const ${toCamel(className)}PageQuerySchema = z.object({
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(100).default(20),
  keyword: z.string().trim().max(100).optional(),
})

export const ${toCamel(className)}CreateSchema = z.object({
${createFields}
})

export const ${toCamel(className)}UpdateSchema = ${toCamel(className)}CreateSchema.partial().extend({
  id: z.string().min(1, "id 不能为空"),
})

export type ${className}PageQueryInput = z.infer<typeof ${toCamel(className)}PageQuerySchema>
export type ${className}CreateInput = z.infer<typeof ${toCamel(className)}CreateSchema>
export type ${className}UpdateInput = z.infer<typeof ${toCamel(className)}UpdateSchema>
`
  return { path: `${getBasePath(config)}/validators/${kebab}.validator.ts`, content, type: "validator" }
}

function generateService(config: CodegenConfig): CodegenOutput {
  const { className, moduleName, businessName } = config
  const kebab = toKebab(className)
  const camel = toCamel(className)

  const content = `// Auto-generated by Codegen Engine
import { domainLog } from "@/modules/shared/backend/lib/domain-log"
import type { ${className}PageQueryInput, ${className}CreateInput, ${className}UpdateInput } from "../validators/${kebab}.validator"

// TODO: Replace mock with real Prisma queries
const MOCK_DATA: any[] = []
let nextId = 100

export class ${className}Service {
  /** 分页查询 */
  static async page(input: ${className}PageQueryInput) {
    domainLog.event("${moduleName}.${camel}.page", { page: input.page, total: MOCK_DATA.length })
    let filtered = [...MOCK_DATA]
    if (input.keyword) {
      const kw = input.keyword.toLowerCase()
      filtered = filtered.filter((item) => JSON.stringify(item).toLowerCase().includes(kw))
    }
    const start = (input.page - 1) * input.pageSize
    return { items: filtered.slice(start, start + input.pageSize), total: filtered.length, page: input.page, pageSize: input.pageSize }
  }

  /** 获取详情 */
  static async get(id: string) {
    const item = MOCK_DATA.find((d) => d.id === id)
    if (!item) throw new Error("${businessName}不存在")
    return item
  }

  /** 创建 */
  static async create(input: ${className}CreateInput) {
    const id = \`${kebab}-\${++nextId}\`
    const item = { id, ...input, created_at: new Date().toISOString() }
    MOCK_DATA.push(item)
    domainLog.event("${moduleName}.${camel}.create", { id })
    domainLog.audit("${moduleName}.${camel}.create", { targetType: "${moduleName.toUpperCase()}_${className.toUpperCase()}", targetId: id })
    return { id }
  }

  /** 更新 */
  static async update(input: ${className}UpdateInput) {
    const idx = MOCK_DATA.findIndex((d) => d.id === input.id)
    if (idx === -1) throw new Error("${businessName}不存在")
    MOCK_DATA[idx] = { ...MOCK_DATA[idx], ...input }
    domainLog.event("${moduleName}.${camel}.update", { id: input.id })
    domainLog.audit("${moduleName}.${camel}.update", { targetType: "${moduleName.toUpperCase()}_${className.toUpperCase()}", targetId: input.id })
    return true
  }

  /** 删除 */
  static async delete(id: string) {
    const idx = MOCK_DATA.findIndex((d) => d.id === id)
    if (idx === -1) throw new Error("${businessName}不存在")
    MOCK_DATA.splice(idx, 1)
    domainLog.event("${moduleName}.${camel}.delete", { id })
    domainLog.audit("${moduleName}.${camel}.delete", { targetType: "${moduleName.toUpperCase()}_${className.toUpperCase()}", targetId: id })
    return true
  }
}
`
  return { path: `${getBasePath(config)}/services/${kebab}.service.ts`, content, type: "service" }
}

function generateRoute(config: CodegenConfig): CodegenOutput {
  const { className, moduleName, subModule } = config
  const kebab = toKebab(className)
  const camel = toCamel(className)
  const sub = subModule ? `/${subModule}` : ""

  const content = `// Auto-generated by Codegen Engine
import { NextResponse } from "next/server"
import { ${className}Service } from "@/modules/${moduleName}${sub}/services/${kebab}.service"
import { ${camel}PageQuerySchema, ${camel}CreateSchema, ${camel}UpdateSchema } from "@/modules/${moduleName}${sub}/validators/${kebab}.validator"
import { ensurePermission } from "@/modules/shared/backend/lib/permission-guard"
import { PERMISSIONS } from "@/modules/shared/backend/constants/permissions"

export async function GET(request: Request) {
  try {
    const { searchParams } = new URL(request.url)
    const id = searchParams.get("id")
    if (id) {
      const data = await ${className}Service.get(id)
      return NextResponse.json({ success: true, data })
    }
    const input = ${camel}PageQuerySchema.parse({
      page: searchParams.get("page") || 1,
      pageSize: searchParams.get("pageSize") || 20,
      keyword: searchParams.get("keyword") || undefined,
    })
    const data = await ${className}Service.page(input)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message || "查询失败" }, { status: 400 })
  }
}

export async function POST(request: Request) {
  try {
    const body = await request.json()
    const input = ${camel}CreateSchema.parse(body)
    const data = await ${className}Service.create(input)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message || "创建失败" }, { status: 400 })
  }
}

export async function PUT(request: Request) {
  try {
    const body = await request.json()
    const input = ${camel}UpdateSchema.parse(body)
    const data = await ${className}Service.update(input)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message || "更新失败" }, { status: 400 })
  }
}

export async function DELETE(request: Request) {
  try {
    const { searchParams } = new URL(request.url)
    const id = searchParams.get("id")
    if (!id) return NextResponse.json({ success: false, error: "id 不能为空" }, { status: 400 })
    const data = await ${className}Service.delete(id)
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message || "删除失败" }, { status: 400 })
  }
}
`
  return { path: `src/app/api/v1/admin/${moduleName}/${kebab}/route.ts`, content, type: "route" }
}

function generateListPage(config: CodegenConfig): CodegenOutput {
  const { className, moduleName, businessName, table, subModule } = config
  const kebab = toKebab(className)
  const sub = subModule ? `/${subModule}` : ""

  const columns = table.columns
    .filter((c) => c.name !== "deleted" && c.uiComponent !== "HIDDEN")
    .slice(0, 8) // 列表最多显示 8 列
    .map((c) => `    { key: "${c.name}", label: "${c.comment || c.name}" },`)
    .join("\n")

  const content = `// Auto-generated by Codegen Engine
"use client"

import { AdminListPageTemplate } from "@/modules/shared/frontend/templates/admin-list-page.template"

const columns = [
${columns}
]

export default function ${className}ListPage() {
  return (
    <AdminListPageTemplate
      title="${businessName}管理"
      endpoint="/api/v1/admin/${moduleName}/${kebab}"
    />
  )
}
`
  return { path: `${getBasePath(config)}/frontend${sub ? "/" + subModule : ""}/pages/${kebab}-list.page.tsx`, content, type: "page" }
}

function generateFormComponent(config: CodegenConfig): CodegenOutput {
  const { className, table, businessName } = config
  const kebab = toKebab(className)

  const formFields = table.columns
    .filter((c) => !c.isPrimary && !c.isAutoIncrement && c.name !== "created_at" && c.name !== "updated_at" && c.name !== "deleted")
    .map((c) => {
      return `      <div>
        <label className="block text-sm font-medium mb-1">${c.comment || c.name}</label>
        <input name="${c.name}" placeholder="${c.comment || c.name}" className="w-full h-9 rounded border px-3 text-sm" ${!c.nullable ? "required" : ""} />
      </div>`
    })
    .join("\n")

  const content = `// Auto-generated by Codegen Engine
"use client"

import { useState } from "react"

type Props = {
  mode: "create" | "edit"
  initialData?: Record<string, any>
  onSubmit: (data: Record<string, any>) => void
  onCancel: () => void
}

export function ${className}Form({ mode, initialData, onSubmit, onCancel }: Props) {
  const [loading, setLoading] = useState(false)

  const handleSubmit = async (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault()
    setLoading(true)
    const formData = new FormData(e.currentTarget)
    const data = Object.fromEntries(formData.entries())
    if (mode === "edit" && initialData?.id) data.id = initialData.id
    onSubmit(data)
    setLoading(false)
  }

  return (
    <form onSubmit={handleSubmit} className="space-y-4">
      <h3 className="text-lg font-semibold">{mode === "create" ? "新增" : "编辑"}${businessName}</h3>
${formFields}
      <div className="flex gap-2 pt-4">
        <button type="submit" disabled={loading} className="h-9 px-4 rounded bg-slate-900 text-white text-sm">
          {loading ? "提交中..." : "确定"}
        </button>
        <button type="button" onClick={onCancel} className="h-9 px-4 rounded border text-sm">取消</button>
      </div>
    </form>
  )
}
`
  return { path: `${getBasePath(config)}/frontend/components/${kebab}-form.tsx`, content, type: "component" }
}

