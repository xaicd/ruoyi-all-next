import {
  type CodegenConfig,
  type CodegenOutput,
  getBackendPath,
  toCamel,
  toConstant,
  toKebab,
} from "./common"

function generateManagedOnlineService(config: CodegenConfig): CodegenOutput {
  const { className, businessName } = config
  const kebab = toKebab(className)
  const camel = toCamel(className)
  const constName = toConstant(className)
  const domain = config.onlineRuntime?.domain || config.moduleName
  const tableId = config.onlineRuntime?.tableId || config.table.name

  const content = `// Auto-generated by Codegen Engine (Online Managed Table Facade)
import { onlinePlatformFacade, onlinePlatformFacade as onlineFacade } from "@/modules/online/contract/online-platform.facade"
import { domainLog } from "@/modules/shared/backend/lib/domain-log"
import type {
  ${className}CreateDTO,
  ${className}PageQuery,
  ${className}UpdateDTO,
} from "../types/${kebab}.types"

const DOMAIN = ${JSON.stringify(domain)}
const TABLE_ID = ${JSON.stringify(tableId)}

export class ${className}Service {
  static async page(query: ${className}PageQuery, actorId?: string, tenantId?: string) {
    const page = query.page ?? 1
    const pageSize = query.pageSize ?? 20
    const filter = { ...query }
    delete (filter as Record<string, unknown>).page
    delete (filter as Record<string, unknown>).pageSize

    // Calls onlineFacade to page managed records
    return onlineFacade.queryManagedRecords({
      domain: DOMAIN,
      tableId: TABLE_ID,
      page,
      pageSize,
      filter: Object.keys(filter).length ? (filter as Record<string, unknown>) : undefined,
    }, { actorId, tenantId })
  }

  static async pageManagedRecords(query: ${className}PageQuery, actorId?: string, tenantId?: string) {
    return this.page(query, actorId, tenantId)
  }

  static async get(id: string, actorId?: string, tenantId?: string) {
    return onlinePlatformFacade.getManagedRecord({
      domain: DOMAIN,
      tableId: TABLE_ID,
      id,
    }, { actorId, tenantId })
  }

  static async create(data: ${className}CreateDTO, actorId?: string, tenantId?: string) {
    const record = await onlinePlatformFacade.insertManagedRecord({
      domain: DOMAIN,
      tableId: TABLE_ID,
      data: data as Record<string, unknown>,
    }, { actorId, tenantId })
    domainLog.event("${domain}", "${constName}_CREATED", "创建${businessName}", { id: record.id, actorId })
    return record
  }

  static async update(id: string, data: ${className}UpdateDTO, actorId?: string, tenantId?: string) {
    const record = await onlinePlatformFacade.updateManagedRecord({
      domain: DOMAIN,
      tableId: TABLE_ID,
      id,
      data: data as Record<string, unknown>,
    }, { actorId, tenantId })
    domainLog.event("${domain}", "${constName}_UPDATED", "更新${businessName}", { id, actorId })
    return record
  }

  static async delete(id: string, actorId?: string, tenantId?: string) {
    const ok = await onlinePlatformFacade.deleteManagedRecord({
      domain: DOMAIN,
      tableId: TABLE_ID,
      id,
    }, { actorId, tenantId })
    if (ok) {
      domainLog.event("${domain}", "${constName}_DELETED", "删除${businessName}", { id, actorId })
    }
    return ok
  }
}

export const ${camel}Service = ${className}Service
`
  return { path: `${getBackendPath(config)}/services/${kebab}.service.ts`, content, type: "service" }
}

export function generateService(config: CodegenConfig): CodegenOutput {
  if (config.onlineRuntime?.storageKind === "MANAGED_TABLE") return generateManagedOnlineService(config)
  const { className, moduleName, businessName } = config
  const kebab = toKebab(className)
  const camel = toCamel(className)
  const constName = toConstant(className)

  const content = `// Auto-generated by Codegen Engine
// Rule: Cross-domain callers must use createDomainFacade; never import this Service directly.
import { domainLog } from "@/modules/shared/backend/lib/domain-log"
import { ${className}Repository } from "../repositories/${kebab}.repository"
import type {
  ${className}CreateDTO,
  ${className}PageQuery,
  ${className}UpdateDTO,
} from "../types/${kebab}.types"

export class ${className}Service {
  static async page(query: ${className}PageQuery, actorId?: string, tenantId?: string) {
    const page = query.page ?? 1
    const pageSize = query.pageSize ?? 20
    const filter = { ...query }
    delete (filter as Record<string, unknown>).page
    delete (filter as Record<string, unknown>).pageSize

    return ${className}Repository.page(
      { page, pageSize, ...filter },
      { actorId, tenantId }
    )
  }

  static async get(id: string, actorId?: string, tenantId?: string) {
    return ${className}Repository.findById(id, { actorId, tenantId })
  }

  static async create(data: ${className}CreateDTO, actorId?: string, tenantId?: string) {
    const row = await ${className}Repository.create(data as unknown as Record<string, unknown>, { actorId, tenantId })
    domainLog.event("${moduleName}.${camel}.created", { id: row.id, actorId })
    return row
  }

  static async update(id: string, data: ${className}UpdateDTO, actorId?: string, tenantId?: string) {
    const row = await ${className}Repository.update(id, data as unknown as Record<string, unknown>, { actorId, tenantId })
    domainLog.event("${moduleName}.${camel}.updated", { id, actorId })
    return row
  }

  static async delete(id: string, actorId?: string, tenantId?: string) {
    const ok = await ${className}Repository.delete(id, { actorId, tenantId })
    if (ok) {
      domainLog.event("${moduleName}.${camel}.deleted", { id, actorId })
    }
    return ok
  }
}

export const ${camel}Service = ${className}Service
`
  return { path: `${getBackendPath(config)}/services/${kebab}.service.ts`, content, type: "service" }
}
