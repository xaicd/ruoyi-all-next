import {
  type CodegenConfig,
  type CodegenOutput,
  getBackendPath,
  toCamel,
  toKebab,
} from "./common"

export function generateRpc(config: CodegenConfig): CodegenOutput {
  const { className, moduleName } = config
  const kebab = toKebab(className)
  const camel = toCamel(className)

  const content = `// Auto-generated by Codegen Engine (RPC Facade / Dual-Mode Binding)
import { serviceBus } from "@/modules/shared/backend/lib/service-bus"
import { ${className}Service } from "./${kebab}.service"
import type {
  ${className}CreateDTO,
  ${className}PageQuery,
  ${className}UpdateDTO,
} from "../types/${kebab}.types"

export class ${className}Rpc {
  static async register() {
    serviceBus.registerHandler("ruoyi.cmd.${moduleName}.${camel}.page", async (req) => {
      const query = req.data as ${className}PageQuery
      return ${className}Service.page(query, req.actorId, req.tenantId)
    })

    bus.registerHandler("ruoyi.cmd.${moduleName}.${camel}.get", async (req) => {
      const { id } = req.data as { id: string }
      return ${className}Service.get(id, req.actorId, req.tenantId)
    })

    bus.registerHandler("ruoyi.cmd.${moduleName}.${camel}.create", async (req) => {
      const data = req.data as ${className}CreateDTO
      return ${className}Service.create(data, req.actorId, req.tenantId)
    })

    bus.registerHandler("ruoyi.cmd.${moduleName}.${camel}.update", async (req) => {
      const { id, ...rest } = req.data as ${className}UpdateDTO
      return ${className}Service.update(id, rest as any, req.actorId, req.tenantId)
    })

    bus.registerHandler("ruoyi.cmd.${moduleName}.${camel}.delete", async (req) => {
      const { id } = req.data as { id: string }
      return ${className}Service.delete(id, req.actorId, req.tenantId)
    })
  }
}

export const ${camel}Rpc = ${className}Rpc
`
  return { path: `${getBackendPath(config)}/services/${kebab}.rpc.ts`, content, type: "rpc" }
}
