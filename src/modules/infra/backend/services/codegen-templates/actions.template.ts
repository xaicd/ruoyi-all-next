import {
  type CodegenConfig,
  type CodegenOutput,
  toCamel,
  toConstant,
  toKebab,
  toPascal,
} from "./common"

export function generateActions(config: CodegenConfig): CodegenOutput {
  const { className, moduleName, submodule } = config
  const sub = submodule ? `/${submodule}` : ""
  const kebab = toKebab(className)
  const camel = toCamel(className)
  const constName = toConstant(className)
  const pascal = toPascal(className)

  const content = `// Auto-generated by Codegen Engine (Contract Actions)
import { z } from "zod"
import {
  ${camel}CreateSchema,
  ${camel}PageQuerySchema,
  ${camel}UpdateSchema,
} from "../backend/validators/${kebab}.validator"

export const ${camel}ActionSchemas = {
  "ruoyi.cmd.${moduleName}.${camel}.page": ${camel}PageQuerySchema,
  "ruoyi.cmd.${moduleName}.${camel}.get": z.object({ id: z.string() }),
  "ruoyi.cmd.${moduleName}.${camel}.create": ${camel}CreateSchema,
  "ruoyi.cmd.${moduleName}.${camel}.update": ${camel}UpdateSchema,
  "ruoyi.cmd.${moduleName}.${camel}.delete": z.object({ id: z.string() }),
  "${moduleName}.page${pascal}": ${camel}PageQuerySchema,
  "${moduleName}.get${pascal}": z.object({ id: z.string() }),
  "${moduleName}.create${pascal}": ${camel}CreateSchema,
  "${moduleName}.update${pascal}": ${camel}UpdateSchema,
  "${moduleName}.delete${pascal}": z.object({ id: z.string() }),
} as const

export const ${constName}_ACTION_SCHEMAS = ${camel}ActionSchemas

export function registerActionSchemas() {
  return ${camel}ActionSchemas
}
`
  return { path: `src/modules/${moduleName}${sub}/contract/${kebab}.actions.ts`, content, type: "type" }
}
