import { NextResponse } from "next/server"
import { CluesService } from "@/modules/crm/backend/services/clues.service"
import { CRM_ACTION_SCHEMAS } from "@/modules/crm/contract/actions"
import { parseActionQuery } from "@/modules/shared/backend/http/parse-action-input"

export async function GET(request: Request) {
  try {
    const data = await CluesService.page(parseActionQuery(CRM_ACTION_SCHEMAS["crm.listClues"], request))
    return NextResponse.json({ success: true, data })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message || "查询失败" }, { status: 400 })
  }
}

export async function POST(request: Request) {
  try {
    const body = await request.json()
    const data = await CluesService.create(body)
    return NextResponse.json({ success: true, data }, { status: 201 })
  } catch (error: any) {
    return NextResponse.json({ success: false, error: error?.message || "创建失败" }, { status: 400 })
  }
}
