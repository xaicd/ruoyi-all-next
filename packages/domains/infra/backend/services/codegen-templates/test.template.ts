import {
  type CodegenConfig,
  type CodegenOutput,
  formColumns,
  getBackendPath,
  toCamel,
  toKebab,
} from "./common"

export function generateTest(config: CodegenConfig): CodegenOutput {
  const { className, businessName } = config
  const kebab = toKebab(className)
  const writeCols = formColumns(config)
  const firstCol = writeCols[0]?.name || "name"

  const content = `// Auto-generated by Codegen Engine (Service Unit Test)
import { describe, it, expect } from "vitest"
import { ${className}Service } from "../${kebab}.service"

describe("${className}Service", () => {
  it("should create and query ${businessName}", async () => {
    const created = await ${className}Service.create({
      ${firstCol}: "测试${businessName}",
    } as any)
    expect(created).toBeDefined()
    expect(created.id).toBeDefined()

    const list = await ${className}Service.page({ page: 1, pageSize: 10 })
    expect(list.items.length).toBeGreaterThan(0)

    const fetched = await ${className}Service.get(created.id)
    expect(fetched).toBeDefined()
    expect(fetched?.id).toBe(created.id)

    const updated = await ${className}Service.update(created.id, {
      id: created.id,
      ${firstCol}: "更新${businessName}",
    } as any)
    expect(updated).toBeDefined()

    const deleted = await ${className}Service.delete(created.id)
    expect(deleted).toBe(true)
  })
})
`
  return { path: `${getBackendPath(config)}/services/__tests__/${kebab}.service.test.ts`, content, type: "test" }
}
