import {
  type CodegenConfig,
  type CodegenOutput,
  toKebab,
} from "./common"

export function generateAppPage(config: CodegenConfig): CodegenOutput {
  const { className, moduleName, submodule } = config
  const sub = submodule ? `/${submodule}` : ""
  const kebab = toKebab(className)

  const content = `// Auto-generated by Codegen Engine (App Router Page)
import { ${className}ListPage } from "@/modules/${moduleName}${sub}/frontend/pages/${kebab}-list.page"

export default function Page() {
  return <${className}ListPage />
}
`
  return { path: `src/app/(admin-pages)/admin/${moduleName}${sub}/${kebab}/page.tsx`, content, type: "appPage" }
}
